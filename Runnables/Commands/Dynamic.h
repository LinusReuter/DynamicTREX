class LoadAndApplyDynamicPartition : public ParameterizedCommand {
public:
    LoadAndApplyDynamicPartition(BasicShell& shell)
        : ParameterizedCommand(
              shell, "loadAndApplyDynamicPartition",
              "Loads a partition file generated by a black-box partitioner and applies the cell ids to the stops.") {
        addParameter("Input partition file");
        addParameter("Input binary (DynamicTimeTable Data)");
        // 0 = derive from the cell ids (bit width of the largest id), which is what the
        // partitioner's output already encodes. Override only to force a smaller hierarchy.
        addParameter("Number of levels", "0");
    }

    virtual void execute() noexcept override {
        const std::string partitionFile = getParameter("Input partition file");
        const std::string dynamicFile = getParameter("Input binary (DynamicTimeTable Data)");
        const int numberOfLevels = getParameter<int>("Number of levels");

        DynamicTimeTable::Data dynamicTimeTable(dynamicFile);
        dynamicTimeTable.printInfo();

        dynamicTimeTable.createCompactLayoutGraph();
        dynamicTimeTable.readPartitionFile(partitionFile);
        if (numberOfLevels > 0) dynamicTimeTable.setNumberOfLevels(numberOfLevels);

        if (!dynamicTimeTable.hasPartition()) {
            std::cout << "No partition was applied -- check the partition file." << std::endl;
            return;
        }
        std::cout << "Applied partition: " << dynamicTimeTable.getNumberOfLevels() << " levels over "
                  << dynamicTimeTable.numberOfStops() << " stops." << std::endl;
        if (!dynamicTimeTable.assertNoCutTransfers()) {
            std::cout << "WARNING: the partition cuts at least one footpath; TREX cell "
                         "restriction assumes footpaths stay inside a cell."
                      << std::endl;
        }

        dynamicTimeTable.serialize(dynamicFile);
    }
};

